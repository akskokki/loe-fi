/**
 * A small seeded random generator (mulberry32): the same seed gives the same numbers, so a test or
 * harness run that fails can be repeated exactly. Returns numbers in [0, 1) like Math.random.
 */
export function seededRandom(seed: number): () => number {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 2 ** 32;
  };
}
